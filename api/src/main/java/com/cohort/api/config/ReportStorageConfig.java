package com.cohort.api.config;

import com.cohort.api.service.resume.storage.FileStorageStrategy;
import com.cohort.api.service.resume.storage.LocalFileStorageImpl;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;

/**
 * FR-104 ("the same storage rules as resumes"): report files go through the
 * very same {@link FileStorageStrategy} implementation resumes use --
 * server-generated keys, path-traversal checks, outside the web root -- just
 * rooted in their own directory. Deliberately the <em>undecorated</em>
 * strategy: {@code ValidatingFileStorage}'s upload checks (PDF/DOCX magic
 * bytes, 5 MB cap) exist to vet untrusted user uploads, whereas these files
 * are generated by the server itself.
 */
@Configuration
public class ReportStorageConfig {

    @Bean
    public FileStorageStrategy reportFileStorage(@Value("${app.report-storage.base-dir:./data/reports}") String baseDir) {
        return new LocalFileStorageImpl(baseDir);
    }
}
